def test_the_measured_span_is_large_enough_for_the_bound_to_discriminate():
    """A 3 dB bound on a quantity that only moves 1 dB would pass for any
    structure. Every column's TONE span must be at least twice the bound."""
    art = tk.from_artifact()
    for d in tk.CODES:
        span = max(art[d].values()) - min(art[d].values())
