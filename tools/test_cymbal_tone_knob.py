def test_the_linear_law_fits_and_the_three_alternatives_do_not():
    art = tk.from_artifact()
    head = tk.fit_balance(tk.gain_table(mapping="linear"), art)
    assert head["worst_db"] < 0.5, head["worst_db"]
    alts = tk.alternatives(art)
    for name in ("inverted", "no-tone-network", "low-on-top-rail"):
        assert alts[name]["worst_db"] > 4.0, (name, alts[name]["worst_db"])
    # and the one that is NOT excluded, stated rather than omitted
    assert alts["ht2-ht3-swapped"]["worst_db"] < tk.BOUND_DB


def test_the_linear_mapping_is_the_best_of_the_candidates_swept():
    sw = tk.mapping_sweep(tk.from_artifact())
    best = min(sw, key=lambda m: sw[m]["worst_db"])
    assert best == "linear", {m: v["worst_db"] for m, v in sw.items()}
    # ... and how much better, because "best" without a margin is not a result
    second = sorted(v["worst_db"] for v in sw.values())[1]
    assert second - sw["linear"]["worst_db"] < 0.5, sw["upper-half"]["worst_db"]


def test_the_balance_is_only_constrained_in_its_difference():
    """The honest form of "this measures the VCA drives": it does not. The
    admitted region fills the swept grid in both absolute weights."""
    r = tk.balance_region(tk.gain_table(mapping="linear"), tk.from_artifact())
    assert r["decay_db"] == [float(tk.BALANCE_DB[0]), float(tk.BALANCE_DB[-1])]
    assert r["short_db"] == [float(tk.BALANCE_DB[0]), float(tk.BALANCE_DB[-1])]
    lo, hi = r["short_minus_decay_db"]
    assert hi - lo < 20.0, r


