def test_every_alternative_is_an_involution_of_the_configuration():
    """The alternatives are applied to whatever the defect left, so each must be
    its own inverse. This is the mechanism by which a defect is caught at all:
    under `ALPHA_INVERTED` the 'inverted' alternative has to become the TRUTH."""
    for alt in tk.ALTERNATIVES:
        base = tk.config()
        once = tk.config(alternative=alt)
        assert once != base, alt
        twice = tk.config(alternative=alt, mapping=once["mapping"])
        twice["rails"] = tk._swap(once["rails"],
                                  *{"low-on-top-rail": ("low", "short"),
                                    "ht2-ht3-swapped": ("decay", "short")}.get(alt, ("low", "low")))
        twice["tone_flat"] = (not once["tone_flat"]) if alt == "no-tone-network" else once["tone_flat"]
        assert twice["rails"] == base["rails"], alt
        assert twice["mapping"] == base["mapping"], alt
        assert twice["tone_flat"] == base["tone_flat"], alt


