_MEAS: dict = {}


def _maybe_measured():
    """The windowed measurement if the corpus is here, else None -- so the
    blindness assertions about the strike and tail windows are decided rather
    than skipped wherever the WAVs exist."""
    if "v" not in _MEAS:
        refs = tk.rc.configured_refs()
        _MEAS["v"] = (tk.measure_windows(refs) if (refs / "cy8").is_dir() else None)
    return _MEAS["v"]


@pytest.mark.parametrize("defect,blind", sorted(
    (d, p) for d, ps in tk.BLIND_PAIRS.items() for p in ps))
def test_each_asserted_blindness_is_verified_blind(defect, blind):
    """Rule 4's other half. `RAIL_SWAP_HT2_HT3` is the interesting row: it is
    visible to `tone-exact` and invisible to every alpha-law property, and that
    asymmetry is precisely why this instrument cannot resolve the assignment."""
    m = _maybe_measured()
    clean = tk.properties(meas=m)
    got = tk.properties(meas=(None if defect in tk.CORPUS_DEFECTS else m), defect=defect)
    if clean[blind]["ok"] is None:
        pytest.skip(f"{blind} is not decidable without the corpus")
    assert got[blind]["ok"] == clean[blind]["ok"], (defect, blind,
                                                    clean[blind]["value"], got[blind]["value"])


@pytest.mark.parametrize("blind", tk.BLIND_BY_CONSTRUCTION)
def test_the_globally_blind_control_moves_nothing(blind):
    clean, got = tk.properties(), tk.properties(defect=blind)
    moved = [n for n in tk.PROPERTIES
             if clean[n]["ok"] is not None and got[n]["ok"] != clean[n]["ok"]]
    assert not moved, (blind, moved)


