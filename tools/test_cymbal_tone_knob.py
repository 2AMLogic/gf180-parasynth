def test_the_floor_estimate_is_the_last_100ms_not_a_same_length_window():
    """Wrong-then-right 3, as a permanent control.

    A record 1.5 s long with a 1 s analysis window: the first version compared
    that window against the LAST 1 s of the same record, which on a real cymbal
    is still full of the tail, and reported a 14.7 dB "floor margin" for a
    recording whose floor is 66 dB down. Here the signal is a decaying tone with
    a genuinely tiny floor, and the two conventions are computed side by side.
    """
    sr = 44100
    t = np.arange(int(1.5 * sr)) / sr
    x = np.exp(-t / 0.15) * np.sin(2 * np.pi * 3450 * t) + 1e-4 * np.sin(2 * np.pi * 50 * t)
    sig, floor = tk._floorful_energy(x, sr, 0.0, 1.0)
    implemented = 10 * math.log10(sig / floor)
    same_length = 10 * math.log10(sig / float(np.sum(x[-sr:] ** 2)))
    assert implemented > 50.0, implemented
    assert same_length < 30.0, same_length
    assert implemented - same_length > 20.0, (implemented, same_length)


