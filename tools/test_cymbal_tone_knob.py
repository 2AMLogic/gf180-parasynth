def test_the_bounds_are_the_ones_the_repository_already_states():
    """A bound invented inside the module that uses it is a bound chosen to
    pass. Both of these live somewhere else and are asserted equal here so they
    cannot drift apart silently."""
    assert tk.BOUND_DB == tr.SHAPE_BOUND_DB
    assert tk.FLOOR_MARGIN_DB == cb.TRUNC_MARGIN_DB
    assert tk.WINDOWS["1s"] == (0.0, cb.ENERGY_S)


def test_the_codes_are_in_knob_order_not_filename_order():
    """`cymbal_bands.CODES` is ("00", "10", "25", "50", "75") -- FILENAME order,
    because "10" means 100 %. Reading a trend down that order puts TONE = full
    second and turns a falling quantity into a 109 % rise, which is exactly what
    the first version of `h-edt-falls-with-tone` reported (wrong-then-right 4).
    """
    assert tk.CODES == ("00", "25", "50", "75", "10")
    assert set(tk.CODES) == set(cb.CODES)
    assert [tk.FRAC[c] for c in tk.CODES] == [0.0, 0.25, 0.5, 0.75, 1.0]
    assert all(tk.FRAC[c] == cb.KNOB[c] / 10.0 for c in tk.CODES)


def test_the_pot_is_linear_and_both_ends_are_held_off_the_rail():
    assert tk.alpha_of(0.25) == pytest.approx(0.25)
    assert tk.alpha_of(0.75) == pytest.approx(0.75)
    assert 0.0 < tk.alpha_of(0.0) <= tk.ALPHA_EPS
    assert 1.0 - tk.ALPHA_EPS <= tk.alpha_of(1.0) < 1.0
    assert tk.alpha_of(0.25, mapping="inverted") == pytest.approx(0.75)


def test_the_tone_term_is_the_committed_module_s_own_network():
    """`tone_db` must reproduce `tone_stage_schematic`'s reported values at its
    own fitted wiper position. The same filter written twice, so the tolerance
    is transcription-level and not a fit tolerance."""
    cfg = tk.config()
    for band, want in tk.TONE_EXACT_DB.items():
        got = tk.tone_db(band, np.array(ts.CY_BANDS_HZ), ts.ALPHA_K1, cfg)
        assert got == pytest.approx(want, abs=tk.TONE_EXACT_TOL_DB), (band, got, want)


# ---------------------------------------------------------------------------
# (a) known answers: a planted balance and a planted law read back
# ---------------------------------------------------------------------------
def _synthetic(mapping, balance_db, *, cols=None):
    """H - L at every setting, generated BY the model at a known balance and a
    known alpha(TONE). Every DECAY column is given the same curve because the
    model has no DECAY dependence -- which is itself the point: the TONE law is
    structural, so a column-independent curve is what it predicts."""
    g = tk.gain_table(mapping=mapping)
    y = tk.predicted_hml(g, np.array([0.0, *balance_db]))
    return {d: {t: float(y[i]) for i, t in enumerate(tk.CODES)}
            for d in (cols or tk.CODES)}


@pytest.mark.parametrize("balance", [(10.0, 11.5), (0.0, 0.0), (-6.0, 18.0)])
def test_a_planted_balance_reads_back_from_its_own_curve(balance):
    """The fitter recovers a planted balance to the grid step, with a residual
    at the arithmetic's own noise. If this failed, every number the instrument
    reports would be a number about the fitter rather than about the machine."""
    meas = _synthetic("linear", balance)
    f = tk.fit_balance(tk.gain_table(mapping="linear"), meas)
    assert f["worst_db"] < 1e-6, f
    step = float(tk.BALANCE_DB[1] - tk.BALANCE_DB[0])
    assert f["balance_db"]["decay"] == pytest.approx(balance[0], abs=step)
    assert f["balance_db"]["short"] == pytest.approx(balance[1], abs=step)


def test_the_planted_curve_is_not_flat_so_the_recovery_is_not_vacuous():
    """A known answer that is constant is recovered by anything. The planted
    curve has to span more than the bound it is later judged against, or the
    test above proves only that 0 == 0."""
    meas = _synthetic("linear", (10.0, 11.5))
    span = max(meas["50"].values()) - min(meas["50"].values())
    assert span > 2 * tk.BOUND_DB, span


def test_a_planted_INVERTED_law_is_rejected_by_the_linear_fit():
    """The paired negative. Data generated by the inverted wiper law must MISS
    the bound when the linear law is fitted to it, with the same two free balance
    numbers available."""
    meas = _synthetic("inverted", (10.0, 11.5))
    f = tk.fit_balance(tk.gain_table(mapping="linear"), meas)
    assert f["worst_db"] > tk.BOUND_DB, f["worst_db"]


def test_the_family_CAN_reach_a_flat_curve_and_a_straight_ramp():
    """The uncomfortable half, pinned so it cannot quietly disappear.

    This test was written to fail -- "a flat TONE law must be rejected" -- and it
    did not: at a decay-dominated balance (+36/-30 dB) the same family predicts
    an H - L that barely moves across the whole wiper travel, and a straight ramp
    of the machine's own span is reachable too. So the headline residual is NOT
    on its own decisive, and the module's docstring says so because of this test.
    Wrong-then-right 6."""
    audit = tk.shape_audit(tk.from_artifact())
    assert audit["flat"]["reachable"], audit["flat"]
    assert audit["linear-ramp"]["reachable"], audit["linear-ramp"]
    # ... and the balance that does it is nowhere near the one the machine picks
    assert abs(audit["flat"]["balance_db"]["short"]
               - audit["machine"]["balance_db"]["short"]) > 20.0, audit


def test_the_family_cannot_reach_three_of_the_eight_stated_shapes():
    """The other side of the same measurement, and the one that makes the result
    evidence: reversing the machine's own curve, a step and a V are all out of
    reach of the same two free numbers."""
    audit = tk.shape_audit(tk.from_artifact())
    out = sorted(k for k, v in audit.items() if not v["reachable"])
    assert out == ["machine-reversed", "step", "vee"], audit
    assert audit["machine-reversed"]["worst_db"] > 5.0, audit["machine-reversed"]


