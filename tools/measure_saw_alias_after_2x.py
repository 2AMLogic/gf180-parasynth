# ---------------------------------------------------------------------------
# the frozen reference table
# ---------------------------------------------------------------------------
_SECTION = "3. ALIASING: inharmonic energy, dB of total, at rising pitch"
_HZ_TO_NOTE = {55: 33, 110: 45, 220: 57, 440: 69, 880: 81, 1760: 93}


def parse_report_table(path: pathlib.Path = None) -> dict:
    """Section 3 of `docs/reference-voice-report.txt`, as
    `{(device, wave): {note: {"value": dB|None, "at_floor": bool}}}`.

    `<` in a cell is the report's own mark for "within 3 dB of the ideal row at
    the same waveform and pitch", i.e. the estimator's floor rather than the
    instrument. It is carried through, not dropped: a margin computed from such
    a cell is a lower bound and is labelled one."""
    path = (ROOT / REPORT_PATH) if path is None else pathlib.Path(path)
    if not path.exists():
        raise Refused(f"the frozen reference table {path} is missing; nothing to compare against")
    lines = path.read_text().splitlines()
    try:
        start = next(i for i, ln in enumerate(lines) if _SECTION in ln)
    except StopIteration:
        raise Refused(f"{path} has no section {_SECTION!r}")
    header = None
    out: dict = {}
    for ln in lines[start + 1:]:
        if header is None:
            # The section title is followed by its own rule line; the column
            # header is the first line that names the pitches.
            if ln.startswith("device/wave"):
                header = [int(v) for v in ln.split()[1:]]
            continue
        if ln.startswith("  MARGIN") or ln.strip().startswith("===="):
            break
        m = re.match(r"^(\w+)/(\w+)\s+(.*)$", ln)
        if not m:
            continue
        device, wave, rest = m.group(1), m.group(2), m.group(3)
        cells = re.findall(r"(<?)\s*(-?\d+\.\d+|---)", rest)
        if len(cells) != len(header):
            continue
        row = {}
        for (mark, val), hz in zip(cells, header):
            note = _HZ_TO_NOTE.get(hz)
            if note is None:
                continue
            row[note] = dict(value=None if val == "---" else float(val),
                             at_floor=mark == "<")
        out[(device, wave)] = row
    if not out:
        raise Refused(f"parsed no rows out of section 3 of {path}")
    return out


def live_reference_table() -> dict:
    """--live-refs: re-render Surge XT and Mini V3 here. Refuses loudly on a
    host without the plugins rather than returning an empty table that would
    read as "no aliasing measured"."""
    try:
        import reference_rigs as rr                                 # noqa: F401
        import reference_voice as rv
    except Exception as e:                                          # pragma: no cover
        raise Refused(f"--live-refs: cannot import the rigs: {e}")
    missing = [p for p in (rr.PATH_SURGE, rr.PATH_MINIV3) if not os.path.exists(p)]
    if missing:                                                     # pragma: no cover
        raise Refused("--live-refs: these VST3 bundles are not on this host: "
                      + ", ".join(missing))
    out: dict = {}
    surge, mini = rr.SurgeRig("Type 2"), rr.MiniV3Rig()             # pragma: no cover
    try:                                                            # pragma: no cover
        for name, dev in (("surge", surge), ("miniv3", mini)):
            row = {}
            for note in REFERENCE_NOTES:
                f0 = vf.note_hz(note)
                r = rv.measure(dev.osc_tone("saw", note), f0, f"{name}/saw/{note}", "saw")
                row[note] = dict(value=r.get("inharmonic_db"), at_floor=False)
            out[(name, "saw")] = row
    finally:                                                        # pragma: no cover
        del surge, mini
    return out                                                      # pragma: no cover


# ---------------------------------------------------------------------------
# readings
# ---------------------------------------------------------------------------
def reading(y: np.ndarray, f0: float, what: str) -> dict:
    """One `inharmonic_fraction_db` reading, with its own measured floor beside
    it. `floor_limited` is the only honest answer when headroom is small: the
    number is then a property of the estimator, which is how this issue's whole
    55 Hz column came to be withdrawn."""
    est = am.inharmonic_fraction_db(y, f0, SR)
    if not est.ok:
        return dict(what=what, value=None, refused=est.reason)
    hd = float(est.detail["headroom_db"])
    return dict(what=what, value=round(float(est.value), 2),
                floor_db=round(float(est.detail["floor_db"]), 2),
                headroom_db=round(hd, 2), floor_limited=hd < MIN_HEADROOM_DB,
                window=est.detail["window"], refused=None)


def alias_curve_table() -> list:
    """Before and after at the six registers the locked test uses, plus the
    drop-decimator control that says the improvement is the FILTER and not the
    oversampling."""
    rows = []
    for note in ALIAS_NOTES:
        yb, f0 = render_base(note)
        ya, _ = render_2x(note)
        yd, _ = render_2x_drop(note)
        before = reading(yb, f0, "base rate")
        after = reading(ya, f0, "2x + FIR decimation")
        drop = reading(yd, f0, "2x + drop decimation (control)")
        rows.append(dict(
            note=note, f0_hz=round(f0, 2), before=before, after=after, control_drop=drop,
            improvement_db=None if before["value"] is None or after["value"] is None
            else round(before["value"] - after["value"], 2)))
    return rows


def reference_table(mod, frozen: dict) -> list:
    """The matched-pitch comparison, computed on ONE instrument.

    Both sides go through the frozen table's own estimator, because that is the
    only instrument the Surge and Mini V3 rows exist on. Ours is additionally
    read on today's Blackman-Harris estimator so the two can be seen not to
    disagree -- and, at 55 Hz, seen to disagree exactly where the old one is at
    its floor."""
    rows = []
    for note in REFERENCE_NOTES:
        f0_cmd = vf.note_hz(note)
        y2, f0_inc = render_2x(note)
        yb, _ = render_base(note)
        yi, _ = _ideal("saw", note)
        ours_2x_report = _report_read(mod, y2, f0_cmd)
        ours_base_report = _report_read(mod, yb, f0_cmd)
        ideal_report = _report_read(mod, yi, f0_cmd)
        today = reading(y2, f0_inc, "2x + FIR decimation (blackman-harris)")
        today_base = reading(yb, f0_inc, "base rate (blackman-harris)")
        # The report's own floor rule: within 3 dB of the ideal row is a limit.
        ours_at_floor = (ours_2x_report - ideal_report) < MIN_HEADROOM_DB
        row = dict(note=note, f0_hz=round(f0_cmd, 2),
                   ours_2x_report_db=round(ours_2x_report, 2),
                   ours_base_report_db=round(ours_base_report, 2),
                   ideal_report_db=round(ideal_report, 2),
                   ours_2x_headroom_over_ideal_db=round(ours_2x_report - ideal_report, 2),
                   ours_2x_floor_limited=ours_at_floor,
                   ours_2x_today=today, ours_base_today=today_base,
                   margins={})
        for device in ("surge", "miniv3"):
            cell = frozen.get((device, "saw"), {}).get(note)
            if cell is None or cell["value"] is None:
                row["margins"][device] = dict(reference_db=None, margin_db=None,
                                              kind="no qualified reference row")
                continue
            margin = ours_2x_report - cell["value"]
            if ours_at_floor or cell["at_floor"]:
                kind = "lower bound (a side of this margin is at the estimator's floor)"
            elif device == "miniv3":
                kind = ("lower bound (Mini V3's filter cannot be bypassed and can only "
                        "remove aliases)")
            else:
                kind = "value"
            row["margins"][device] = dict(reference_db=cell["value"],
                                          reference_at_floor=cell["at_floor"],
                                          margin_db=round(margin, 2), kind=kind)
        rows.append(row)
    return rows


