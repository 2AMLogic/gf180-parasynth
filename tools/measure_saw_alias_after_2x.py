def measure(live_refs: bool = False, argv=None) -> dict:
    checks = [assert_stale_json_refused(), assert_shipped_path()]
    frozen = parse_report_table()
    mod = load_report_estimator()
    checks.append(assert_report_instrument(mod, frozen))
    table = live_reference_table() if live_refs else frozen
    alias = alias_curve_table()
    ref = reference_table(mod, table)
    return dict(provenance=provenance(argv), preconditions=checks,
                reference_source=dict(
                    path=REPORT_PATH if not live_refs else "<live rigs>",
                    commit=REPORT_COMMIT if not live_refs else None,
                    date=REPORT_DATE if not live_refs else None,
                    estimator=("hann, as at " + REPORT_COMMIT[:7]) if not live_refs
                    else "blackman-harris (today)",
                    refused=[assert_stale_json_refused()["path"]]),
                alias_curve=alias, reference=ref,
                shape_ranking=shape_ranking(mod, frozen),
                verdict=verdict(alias, ref))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", help="write the JSON result here")
    ap.add_argument("--live-refs", action="store_true",
                    help="re-render Surge XT and Mini V3 (needs the VST3 bundles)")
    args = ap.parse_args(argv)
    try:
        res = measure(live_refs=args.live_refs, argv=sys.argv if argv is None else argv)
    except Refused as e:
        print(f"REFUSED: {e}", file=sys.stderr)
        return 2
    print(format_report(res))
    if args.out:
        pathlib.Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        pathlib.Path(args.out).write_text(json.dumps(res, indent=1, default=str) + "\n")
        print(f"\nwrote {args.out}")
    return 0


