def load_report_estimator(commit: str = REPORT_COMMIT):
    """`model/audio_measure.py` AS IT WAS at the commit that wrote the frozen
    reference table -- Hann-windowed, floor quoted rather than measured.

    Not a reimplementation: the file itself, out of git. A reimplementation is
    a second chance to be wrong about the instrument, which is the class of
    mistake this whole issue is made of."""
    src = subprocess.run(["git", "show", f"{commit}:model/audio_measure.py"],
                         cwd=str(ROOT), capture_output=True, text=True, timeout=60)
    if src.returncode != 0 or not src.stdout.strip():
        raise Refused(f"cannot read model/audio_measure.py at {commit[:7]}: "
                      f"{src.stderr.strip() or 'empty'}")
    tmp = pathlib.Path(tempfile.mkdtemp(prefix="am-report-")) / "audio_measure_report.py"
    tmp.write_text(src.stdout)
    spec = importlib.util.spec_from_file_location("audio_measure_report", tmp)
    mod = importlib.util.module_from_spec(spec)
    # `@dataclass` resolves its own module out of sys.modules while the class
    # body executes, so the module has to be registered before it is run.
    sys.modules["audio_measure_report"] = mod
    spec.loader.exec_module(mod)
    return mod


def _report_read(mod, y: np.ndarray, f0_cmd: float) -> float:
    """One reading through the frozen table's own pipeline: refine f0 from the
    signal (the report does; assuming it was #87's third apparatus fault), then
    the Hann-windowed inharmonic fraction."""
    fe = mod.refine_f0(y, f0_cmd, SR)
    f0 = fe.value if fe.ok else f0_cmd
    est = mod.inharmonic_fraction_db(y, f0, SR)
    if not est.ok:
        raise Refused(f"the report's own estimator refused at f0={f0_cmd:.1f}: {est.reason}")
    return float(est.value)


def assert_report_instrument(mod, table: dict) -> dict:
    """The reconstructed instrument must reproduce the frozen table's OWN rows.

    `ours/saw` and `ideal/saw` are the two rows in that table this host can
    re-render from source, so they are the only available check that the
    reconstruction is the instrument the Surge and Mini V3 rows were read with.
    If they come back, the reference rows are on the same footing as ours and a
    margin means something. If they do not, nothing in the table is comparable
    with anything measured today."""
    checks = []
    worst = 0.0
    for device, render in (("ours", lambda nt: (vf.OscFx("saw", True).render(
            int(SECONDS * SR), vf.phase_inc(vf.note_hz(nt))).astype(np.float64) / FS,
            vf.note_hz(nt))),
            ("ideal", lambda nt: _ideal("saw", nt))):
        row = table.get((device, "saw"))
        if row is None:
            raise Refused(f"the frozen table has no {device}/saw row to check against")
        for note in REFERENCE_NOTES:
            want = row.get(note)
            if want is None or want["value"] is None:
                continue
            y, f0_cmd = render(note)
            got = _report_read(mod, y, f0_cmd)
            d = abs(got - want["value"])
            worst = max(worst, d)
            checks.append(dict(device=device, note=note, frozen=want["value"],
                               reproduced=round(got, 3), delta_db=round(got - want["value"], 3)))
    if worst > REPRODUCTION_TOL_DB:
        raise Refused(
            f"the estimator reconstructed from {REPORT_COMMIT[:7]} does not reproduce "
            f"{REPORT_PATH}'s own ours/saw and ideal/saw rows (worst {worst:.2f} dB > "
            f"{REPRODUCTION_TOL_DB} dB). The frozen reference rows and anything measured "
            "today are then two different measurements and no margin between them is valid.")
    return dict(name="frozen_table_instrument_reproduces_its_own_rows", ok=True,
                commit=REPORT_COMMIT, worst_delta_db=round(worst, 3), rows=checks)


