class Refused(RuntimeError):
    """A precondition failed. This is a first-class outcome, not a failure to
    measure: it means the apparatus was in a state where any number it printed
    would look exactly like data."""


# ---------------------------------------------------------------------------
# provenance
# ---------------------------------------------------------------------------
def _git(*a: str) -> str:
    try:
        return subprocess.run(["git", *a], cwd=str(ROOT), capture_output=True,
                              text=True, timeout=60).stdout.strip()
    except Exception as e:                                          # pragma: no cover
        return f"<unavailable: {e}>"


def provenance(argv=None) -> dict:
    """Every dB figure this repository publishes has to name the commit it was
    measured against (issue #61's own acceptance criteria). `dirty` is part of
    that: a number measured on an uncommitted tree names no commit at all."""
    diff = _git("diff", "HEAD")
    return dict(commit=_git("rev-parse", "HEAD"),
                branch=_git("rev-parse", "--abbrev-ref", "HEAD"),
                dirty=bool(diff),
                command=" ".join(argv or sys.argv),
                utc=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                python=sys.version.split()[0], numpy=np.__version__,
                seconds=SECONDS, warmup_frames=WARMUP, sr=SR)


# ---------------------------------------------------------------------------
# the two renders: base rate, and the shipped 2x-decimated path
# ---------------------------------------------------------------------------
def render_base(note: int, n: int = None, shape: str = "saw") -> tuple[np.ndarray, float]:
    """The base-rate oscillator, exactly as `test_moog_acceptance._osc` builds
    it. `f0` is derived from the QUANTISED increment, not from the commanded
    Hz, because that is the frequency the signal actually has."""
    n = int(SECONDS * SR) if n is None else n
    inc = vf.phase_inc(vf.note_hz(note))
    f0 = inc * SR / (1 << 24)
    return vf.OscFx(shape, True).render(n, inc).astype(np.float64) / FS, f0


def render_2x(note: int, n: int = None, shape: str = "saw",
              warmup: int = WARMUP) -> tuple[np.ndarray, float]:
    """The shipped `oversample_2x=True` oscillator: PolyBLEP at 2x, the 31-tap
    half-band FIR, then every second sample.

    The decimator carries 30 samples of history between calls, so a cold start
    fades the first 30 samples in from silence. `warmup` frames are rendered
    and discarded first, which is what a held note does in the voice."""
    n = int(SECONDS * SR) if n is None else n
    inc = vf.phase_inc(vf.note_hz(note))
    f0 = inc * SR / (1 << 24)
    osc = vf.OscFx(shape, True)
    hist = np.zeros(len(vf._DECIM2_TAPS) - 1, dtype=np.int64)
    phase2 = 0
    if warmup:
        _, hist, phase2 = vf._render_2x(osc, warmup, inc, hist, phase2)
    y, hist, phase2 = vf._render_2x(osc, n, inc, hist, phase2)
    return y.astype(np.float64) / FS, f0


def render_2x_drop(note: int, n: int = None) -> tuple[np.ndarray, float]:
    """CONTROL: the same 2x oscillator reduced by KEEPING THE LAST SUB-STEP
    instead of filtering -- issue #80's defect, and the thing `_DECIM2_TAPS`
    exists to replace. Present so that a green "after" number has something it
    is green *against*: this control must read far worse than the base rate."""
    n = int(SECONDS * SR) if n is None else n
    inc = vf.phase_inc(vf.note_hz(note))
    f0 = inc * SR / (1 << 24)
    hi = vf.OscFx("saw", True).render(2 * n, inc // 2).astype(np.float64) / FS
    return hi[1::2], f0


# ---------------------------------------------------------------------------
# precondition 1: what is measured here is what ships
# ---------------------------------------------------------------------------
def assert_shipped_path(note: int = 76) -> dict:
    """Drive a real `VoiceFx(oversample_2x=True)` note and compare its
    oscillator trace, sample for sample, with the `_render_2x` call this module
    makes on the same increments.

    Not a formality. `voice_fx._render` gates the 2x chain on the SHAPE
    (`saw`, or a rectangle only when `oversample_pulse_2x`), keeps the
    decimator history per oscillator, and advances a second phase accumulator
    for the oscillators that do not take the chain. A module-level helper that
    silently diverged from any of that would measure a path nobody ships."""
    v = vf.VoiceFx(oversample_2x=True)
    v.note(note, 0.6, waves=("saw", "saw", "saw"), detune=(0.0, 0.0, 0.0),
           mix=(1.0, 0.0, 0.0), noise=0.0, drift_cents=0.0,
           mod_mix=0.0, mod_wheel=0.0, glide_s=0)
    shipped = np.asarray(v.trace["osc"][0], dtype=np.int64)
    incs = np.asarray(v.trace["incs"][0], dtype=np.int64)
    osc = vf.OscFx("saw", True)
    hist = np.zeros(len(vf._DECIM2_TAPS) - 1, dtype=np.int64)
    here, _, _ = vf._render_2x(osc, len(shipped), incs, hist, 0)
    worst = int(np.abs(shipped - np.asarray(here, dtype=np.int64)).max())
    if worst != 0:
        raise Refused(
            "the 2x oscillator measured here is NOT the one VoiceFx(oversample_2x=True) "
            f"renders: worst sample difference {worst} LSB at note {note}")
    # ...and the gate is real: with the flag off, the trace must differ.
    w = vf.VoiceFx(oversample_2x=False)
    w.note(note, 0.6, waves=("saw", "saw", "saw"), detune=(0.0, 0.0, 0.0),
           mix=(1.0, 0.0, 0.0), noise=0.0, drift_cents=0.0,
           mod_mix=0.0, mod_wheel=0.0, glide_s=0)
    off = np.asarray(w.trace["osc"][0], dtype=np.int64)
    if np.array_equal(off, shipped):
        raise Refused("oversample_2x=True and oversample_2x=False render the same "
                      "oscillator output -- the flag is not selecting anything")
    return dict(name="shipped_path_is_the_measured_path", ok=True, note=note,
                worst_lsb=worst,
                off_vs_on_max_lsb=int(np.abs(off - shipped).max()))


