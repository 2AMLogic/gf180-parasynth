#!/usr/bin/env python3
"""The sawtooth's aliasing AFTER the 2x decimation filter (issue #61).

    python3 tools/measure_saw_alias_after_2x.py --out docs/saw-alias-2x-results.json

Issue #61 tracked "our oscillators alias 19-32 dB more than both references".
Its own comment trail withdrew most of those magnitudes, the fix direction it
settled on -- a decimation filter, not a longer BLEP -- shipped for the saw
(`voice_fx._render_2x`, `_DECIM2_TAPS`, selected as `OSC2X=1` in
`fpga/SELECTED.md`), and then nobody measured the fixed path against the
references. `model/test_moog_acceptance.py` still locked only the UNFIXED
curve. This is the "after" measurement that docstring said somebody owed.

WHAT THIS MEASURES, AND WHAT IT REFUSES TO MEASURE
--------------------------------------------------
Two register sets, for two different questions, kept apart because they cannot
answer each other's:

  ALIAS_CURVE registers   MIDI 40, 52, 64, 76, 88, 100 -- the six the locked
                          "before" test uses. Base rate vs the 2x-decimated
                          path, ours against ours. No reference reading exists
                          at these pitches and none is invented.
  reference registers     MIDI 33, 45, 57, 69, 81, 93 (55 Hz .. 1760 Hz) --
                          the six `model/reference_voice.py` renders, and the
                          ONLY pitches at which a Surge XT or Mini V3 reading
                          exists in this repository.

**The references are not re-rendered here and cannot be.** `reference_rigs`
hosts VST3 plugins through `dawdreamer` from `/Library/Audio/Plug-Ins/VST3`;
this is a Linux build host with neither. The reference rows are read from the
frozen artefact `docs/reference-voice-report.txt`, whose provenance is checked
before a single margin is computed. If you pass `--live-refs` on a host that
has the plugins, the rigs are used instead and the frozen table becomes the
control.

THREE PRECONDITIONS, ASSERTED AT THE POINT OF USE
-------------------------------------------------
Each one REFUSES rather than reports, because each has already been the cause
of a published wrong number in this repository:

  1. **The 2x path measured here is the path that ships.** The oscillator
     output of a real `VoiceFx(oversample_2x=True)` note is compared sample for
     sample against the `_render_2x` call this module makes. #61's sibling
     lesson: every bench drove the register write port rather than the link.
  2. **The frozen reference table was made with a DIFFERENT estimator.**
     `docs/reference-voice-report.txt` was written by commit 74ce6a0 (#87,
     2026-09-18); `inharmonic_fraction_db` was rewindowed from Hann to
     Blackman-Harris later the same day by ba14af2 (#132), and the report was
     never regenerated. So the report's own instrument is reconstructed from
     its own commit (`git show 74ce6a0:model/audio_measure.py`) and every
     margin against a reference row is computed with THAT instrument, on both
     sides. It is accepted only if it reproduces the report's own `ours/saw`
     and `ideal/saw` rows to 0.15 dB -- if it does not, the two tables are not
     the same measurement and no margin is printed.
  3. **`docs/reference-voice-results.json` is refused outright.** It is the
     machine-readable half of the same study and it was NOT regenerated by
     #87: its Surge rows still read the flat "-60 dB at every pitch" that #87
     identified as the harness's own leftover note tails. Reading it would
     reproduce a withdrawn figure. The refusal is explicit so the next person
     does not have to rediscover it.

Every reading carries `detail['headroom_db']` -- the value above the
estimator's own per-call floor. A reading with less than 3 dB of headroom is
reported as a LIMIT, never as a value, and any margin that uses it is a bound.
The 55 Hz column of this issue was withdrawn once already for exactly this.

Everything here is measurement. It changes no shipped behaviour.
"""
