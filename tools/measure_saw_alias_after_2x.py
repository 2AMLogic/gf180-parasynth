# is the saw still the largest gap?
# ---------------------------------------------------------------------------
# The shapes this voice makes, in the frozen table's own names. `oversample_2x`
# covers `saw` only in the selected baseline: `fpga/SELECTED.md` carries
# OSC2X=1 with PULSE2X=0, so every other shape below is measured on the
# base-rate path, which is what it ships as.
SHAPES = ("saw", "square", "pulse25", "tri", "sine")


def shape_ranking(mod, frozen: dict) -> list:
    """Every waveform's gap to the references, so "the largest known voice
    defect" is re-derived rather than re-asserted after the saw moves.

    Each shape's own `ours/<wave>` row in the frozen table is reproduced here
    first. A shape whose row does not come back is reported as such and ranked
    nowhere -- the alternative is ranking a number this host cannot reproduce.
    The 55 Hz column is excluded from every aggregate: it was withdrawn for
    being the estimator's floor and nothing here revives it."""
    rows = []
    for wave in SHAPES:
        frozen_ours = frozen.get(("ours", wave), {})
        worst = {"surge": None, "miniv3": None, "ideal": None}
        repro = []
        for note in REFERENCE_NOTES:
            if note == 33:
                continue                       # the withdrawn floor-limited column
            f0_cmd = vf.note_hz(note)
            if wave == "sine":
                # `OscFx` has no sine; the voice's sine comes from the same
                # naive table, so render it the way reference_voice does.
                y = _ours_sine(note)
            else:
                y = vf.OscFx(wave, True).render(
                    int(SECONDS * SR), vf.phase_inc(vf.note_hz(note))).astype(np.float64) / FS
            got = _report_read(mod, y, f0_cmd)
            want = frozen_ours.get(note, {}).get("value")
            repro.append(dict(note=note, frozen=want, reproduced=round(got, 2),
                              delta_db=None if want is None else round(got - want, 2)))
            ideal = _report_read(mod, *_ideal(wave, note))
            if got - ideal < MIN_HEADROOM_DB:
                continue                       # ours is at the floor: no margin to take
            # ours-ideal first: the margin against a waveform with no aliasing
            # at all is the one that does not depend on a plugin's settings.
            if worst["ideal"] is None or got - ideal > worst["ideal"]["margin_db"]:
                worst["ideal"] = dict(note=note, f0_hz=round(f0_cmd, 1),
                                      margin_db=round(got - ideal, 2),
                                      ours_db=round(got, 2), reference_db=round(ideal, 2))
            for device in ("surge", "miniv3"):
                cell = frozen.get((device, wave), {}).get(note)
                if cell is None or cell["value"] is None or cell["at_floor"]:
                    continue
                m = got - cell["value"]
                if worst[device] is None or m > worst[device]["margin_db"]:
                    worst[device] = dict(note=note, f0_hz=round(f0_cmd, 1),
                                         margin_db=round(m, 2), ours_db=round(got, 2),
                                         reference_db=cell["value"])
        bad = [r for r in repro if r["delta_db"] is not None and abs(r["delta_db"]) > 1.0]
        rows.append(dict(wave=wave, path="base rate", worst=worst,
                         reproduces_frozen_ours_row=not bad, reproduction=repro))
    # ...and the saw once more, on the path that actually ships for it.
    worst = {"surge": None, "miniv3": None, "ideal": None}
    for note in REFERENCE_NOTES:
        if note == 33:
            continue
        f0_cmd = vf.note_hz(note)
        y2, _ = render_2x(note)
        got = _report_read(mod, y2, f0_cmd)
        ideal = _report_read(mod, *_ideal("saw", note))
        if got - ideal < MIN_HEADROOM_DB:
            continue
        if worst["ideal"] is None or got - ideal > worst["ideal"]["margin_db"]:
            worst["ideal"] = dict(note=note, f0_hz=round(f0_cmd, 1),
                                  margin_db=round(got - ideal, 2),
                                  ours_db=round(got, 2), reference_db=round(ideal, 2))
        for device in ("surge", "miniv3"):
            cell = frozen.get((device, "saw"), {}).get(note)
            if cell is None or cell["value"] is None or cell["at_floor"]:
                continue
            m = got - cell["value"]
            if worst[device] is None or m > worst[device]["margin_db"]:
                worst[device] = dict(note=note, f0_hz=round(f0_cmd, 1),
                                     margin_db=round(m, 2), ours_db=round(got, 2),
                                     reference_db=cell["value"])
    rows.append(dict(wave="saw", path="2x + FIR decimation (OSC2X=1, selected)",
                     worst=worst, reproduces_frozen_ours_row=None, reproduction=[]))
    return rows


def _ours_sine(note: int, n: int = None) -> np.ndarray:
    n = int(SECONDS * SR) if n is None else n
    inc = vf.phase_inc(vf.note_hz(note))
    ph = (np.arange(n, dtype=np.int64) * inc) & vf.PHASE_MASK
    return vf.naive_fx("sine", ph).astype(np.float64) / FS


_IDEAL_KIND = {"saw": ("saw", 0.5), "square": ("pulse", 0.5), "pulse25": ("pulse", 0.25),
               "tri": ("tri", 0.5), "sine": ("sine", 0.5)}


def _ideal(wave: str, note: int, n: int = None) -> tuple[np.ndarray, float]:
    """The alias-free closed form of `wave`, so the estimator's floor for this
    shape and pitch is measured rather than assumed. Same series as
    `reference_voice.ideal_tone`."""
    kind, duty = _IDEAL_KIND[wave]
    n = int(SECONDS * SR) if n is None else n
    f0 = vf.note_hz(note)
    t = np.arange(n) / SR
    y = np.zeros(n)
    k = 1
    while k * f0 < SR / 2:
        if kind == "saw":
            y += np.sin(2 * math.pi * k * f0 * t) / k
        elif kind == "tri":
            if k % 2:
                y += (-1) ** ((k - 1) // 2) * np.sin(2 * math.pi * k * f0 * t) / k ** 2
        elif kind == "sine":
            if k == 1:
                y += np.sin(2 * math.pi * f0 * t)
        else:
            y += math.sin(math.pi * k * duty) * np.cos(2 * math.pi * k * f0 * t) / k
        k += 1
    return y / max(np.abs(y).max(), 1e-12) * 0.5, f0


def verdict(alias_rows: list, ref_rows: list) -> dict:
    """The three questions issue #61's acceptance criteria ask, answered from
    the tables above rather than from a reading of them."""
    b0, b1 = alias_rows[0]["before"]["value"], alias_rows[-1]["before"]["value"]
    a0, a1 = alias_rows[0]["after"]["value"], alias_rows[-1]["after"]["value"]
    octaves = (ALIAS_NOTES[-1] - ALIAS_NOTES[0]) / 12.0
    usable = [r for r in ref_rows if not r["ours_2x_floor_limited"]]
    out = dict(
        before_slope_db_per_octave=round((b1 - b0) / octaves, 2),
        after_slope_db_per_octave=round((a1 - a0) / octaves, 2),
        improvement_db=dict(
            best=max(r["improvement_db"] for r in alias_rows),
            worst=min(r["improvement_db"] for r in alias_rows)),
        floor_limited_rows=[r["note"] for r in ref_rows if r["ours_2x_floor_limited"]])
    for device in ("surge", "miniv3"):
        ms = [r["margins"][device]["margin_db"] for r in usable
              if r["margins"][device]["margin_db"] is not None]
        out[f"gap_to_{device}_db"] = dict(min=min(ms), max=max(ms)) if ms else None
    return out


